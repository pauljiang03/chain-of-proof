"""Write eval/RESULTS.md: the per-question table of the full-answer-key run.

    python3 -m eval.results_md
"""
from __future__ import annotations

import json
import sys
from collections import OrderedDict
from pathlib import Path

from eval import score as scorer

HERE = Path(__file__).resolve().parent


def rows(results: dict, run_items=None):
    by_q = OrderedDict()
    for e in results["extraction"]:
        q = by_q.setdefault((e.get("book", "open"), e["question"]),
                            {"rows": 0, "match": 0, "time_differs": 0, "missing": 0,
                             "not_expressible": 0, "certified": 0})
        q["rows"] += 1
        q[e["status"]] += 1
        if run_items and run_items.get(e["id"]):
            q["certified"] += 1
    return by_q


def main() -> int:
    results = json.loads((HERE / "results_full.json").read_text())
    certified = {i["id"]: i["certified"] for i in results["run"]["items"]}
    by_q = rows(results, certified)
    L = ["# Results against the full NIST answer key", "",
         f"Evidence `{results['evidence']['sha256'][:16]}…` ({results['evidence']['facts']} records), "
         f"{len(results['extraction'])} answer rows, time tolerance {results['reference']['tolerance_s']} s. "
         "Generated by `python3 -m eval.results_md` from `eval/results_full.json`; scored once.", "",
         "- **match**: a record of the expected kind, for that entity, at that time",
         "- **time off**: the record is there with a different time",
         "- **no kind**: the answer is something no record kind can state (a conclusion, a picture)",
         "- **certified**: the row is stated by a finding the deterministic miner got certified", ""]
    for book, title in (("closed", "Closed book: readers built without the answer key"),
                        ("open", "Open book: readers written with the answer key open")):
        L += [f"## {title}", "", "| Question | Rows | Match | Time off | Missing | No kind | Certified |",
              "|---|---:|---:|---:|---:|---:|---:|"]
        tot = {k: 0 for k in ("rows", "match", "time_differs", "missing", "not_expressible", "certified")}
        for (b, q), c in by_q.items():
            if b != book:
                continue
            L.append(f"| Q{q} {scorer.QUESTION_NAMES.get(int(q), '')} | {c['rows']} | {c['match']} | "
                     f"{c['time_differs']} | {c['missing']} | {c['not_expressible']} | {c['certified']} |")
            for k in tot:
                tot[k] += c[k]
        L += [f"| **Total** | **{tot['rows']}** | **{tot['match']}** | {tot['time_differs']} | "
              f"{tot['missing']} | {tot['not_expressible']} | **{tot['certified']}** |", ""]
    (HERE / "RESULTS.md").write_text("\n".join(L) + "\n")
    print(f"{HERE / 'RESULTS.md'}: {len(by_q)} questions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
